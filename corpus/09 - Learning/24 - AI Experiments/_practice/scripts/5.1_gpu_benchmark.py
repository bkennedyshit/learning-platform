#!/usr/bin/env python3
"""
5.1_gpu_benchmark.py — GPU infrastructure validation and benchmarking.

Validates CUDA setup, benchmarks compute TFLOPS and memory bandwidth,
and emits a markdown report.

Usage:
  python 5.1_gpu_benchmark.py --demo
  python 5.1_gpu_benchmark.py --config benchmark_config.yaml
  python 5.1_gpu_benchmark.py --demo --out ./reports/gpu_report.md

Designed for a single 24GB GPU (RTX 4090 / RTX 3090).
"""

from __future__ import annotations

import argparse
import json
import time
from dataclasses import dataclass, field
from datetime import datetime
from pathlib import Path

import torch


@dataclass
class BenchmarkResult:
    name: str
    value: float
    unit: str
    metadata: dict = field(default_factory=dict)


def gpu_info() -> dict:
    """Collect GPU information."""
    info = {
        "pytorch_version": torch.__version__,
        "cuda_available": torch.cuda.is_available(),
        "cuda_version": torch.version.cuda,
        "cudnn_version": torch.backends.cudnn.version(),
        "device_count": torch.cuda.device_count(),
        "devices": [],
    }
    for i in range(torch.cuda.device_count()):
        props = torch.cuda.get_device_properties(i)
        free, total = torch.cuda.mem_get_info(i)
        info["devices"].append({
            "index": i,
            "name": props.name,
            "compute_capability": f"{props.major}.{props.minor}",
            "total_memory_gb": round(total / 1024**3, 2),
            "free_memory_gb": round(free / 1024**3, 2),
            "sm_count": props.multi_processor_count,
        })
    return info


def benchmark_matmul(M=4096, N=4096, K=4096, dtype=torch.float16,
                     warmup=10, iters=100) -> BenchmarkResult:
    """Benchmark matrix multiplication TFLOPS."""
    device = torch.device("cuda")
    A = torch.randn(M, K, dtype=dtype, device=device)
    B = torch.randn(K, N, dtype=dtype, device=device)

    for _ in range(warmup):
        torch.mm(A, B)
    torch.cuda.synchronize()

    start = time.perf_counter()
    for _ in range(iters):
        torch.mm(A, B)
    torch.cuda.synchronize()
    elapsed = time.perf_counter() - start

    flops_per_iter = 2 * M * N * K
    tflops = flops_per_iter * iters / elapsed / 1e12

    return BenchmarkResult(
        name=f"MatMul {M}x{K}x{N} ({dtype})",
        value=round(tflops, 1),
        unit="TFLOPS",
        metadata={"M": M, "N": N, "K": K, "dtype": str(dtype),
                  "ms_per_iter": round(elapsed / iters * 1000, 2)},
    )


def benchmark_bandwidth(size_gb=1.0, dtype=torch.float16, iters=50) -> BenchmarkResult:
    """Measure effective memory bandwidth."""
    device = torch.device("cuda")
    elem_size = torch.tensor([], dtype=dtype).element_size()
    num_elements = int(size_gb * 1024**3 / elem_size)

    src = torch.randn(num_elements, dtype=dtype, device=device)
    dst = torch.empty_like(src)

    for _ in range(5):
        dst.copy_(src)
    torch.cuda.synchronize()

    start = time.perf_counter()
    for _ in range(iters):
        dst.copy_(src)
    torch.cuda.synchronize()
    elapsed = time.perf_counter() - start

    bytes_per_iter = 2 * src.nelement() * elem_size
    bandwidth = bytes_per_iter * iters / elapsed / 1e9

    return BenchmarkResult(
        name=f"Memory Bandwidth ({size_gb} GB, {dtype})",
        value=round(bandwidth, 0),
        unit="GB/s",
        metadata={"size_gb": size_gb, "dtype": str(dtype)},
    )


def render_report(info: dict, results: list[BenchmarkResult], seed: int) -> str:
    """Render benchmark results as markdown."""
    lines = [
        "---",
        "tags: [ai-experiments, gpu-benchmark, practice]",
        "chapter: 5.1",
        "type: benchmark-report",
        f"generated: {datetime.now().isoformat(timespec='seconds')}",
        "---\n",
        "# GPU Benchmark Report\n",
        f"> Generated by `5.1_gpu_benchmark.py` on {datetime.now().strftime('%Y-%m-%d %H:%M')}\n",
        "## System Info\n",
        f"- PyTorch: {info['pytorch_version']}",
        f"- CUDA: {info['cuda_version']}",
        f"- cuDNN: {info['cudnn_version']}",
        f"- Devices: {info['device_count']}\n",
    ]

    for dev in info["devices"]:
        lines.append(f"### GPU {dev['index']}: {dev['name']}")
        lines.append(f"- Compute: {dev['compute_capability']}")
        lines.append(f"- Memory: {dev['total_memory_gb']} GB (free: {dev['free_memory_gb']} GB)")
        lines.append(f"- SMs: {dev['sm_count']}\n")

    lines.append("## Benchmark Results\n")
    lines.append("| Test | Result | Unit | ms/iter |")
    lines.append("|------|--------|------|---------|")
    for r in results:
        ms = r.metadata.get("ms_per_iter", "—")
        lines.append(f"| {r.name} | **{r.value}** | {r.unit} | {ms} |")

    lines.append("\n## Interpretation\n")
    lines.append("- RTX 4090 theoretical FP16: 330 TFLOPS")
    lines.append("- RTX 4090 theoretical bandwidth: 1008 GB/s")
    lines.append("- Achieving >85% of theoretical = healthy GPU\n")

    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description="GPU benchmark and validation")
    parser.add_argument("--demo", action="store_true", help="Run quick demo benchmark")
    parser.add_argument("--config", type=Path, default=None, help="YAML/JSON config file")
    parser.add_argument("--out", type=Path, default=None, help="Output markdown report path")
    args = parser.parse_args()

    if not torch.cuda.is_available():
        print("ERROR: CUDA not available. Check your PyTorch installation.")
        return

    info = gpu_info()
    print(f"GPU: {info['devices'][0]['name']} ({info['devices'][0]['total_memory_gb']} GB)")

    # Load config or use defaults
    sizes = [2048, 4096]
    if args.config and args.config.exists():
        with open(args.config) as f:
            cfg = json.load(f)
            sizes = cfg.get("matmul_sizes", sizes)

    if args.demo:
        sizes = [2048, 4096]

    # Run benchmarks
    results = []
    print("\nRunning benchmarks...")

    for size in sizes:
        r = benchmark_matmul(M=size, N=size, K=size, dtype=torch.float16,
                            warmup=5, iters=50 if args.demo else 100)
        results.append(r)
        print(f"  {r.name}: {r.value} {r.unit}")

    # FP32 comparison
    r = benchmark_matmul(M=2048, N=2048, K=2048, dtype=torch.float32,
                        warmup=5, iters=50)
    results.append(r)
    print(f"  {r.name}: {r.value} {r.unit}")

    # Bandwidth
    r = benchmark_bandwidth(size_gb=0.5 if args.demo else 1.0)
    results.append(r)
    print(f"  {r.name}: {r.value} {r.unit}")

    # Generate report
    out_path = args.out or Path(__file__).parent.parent / "5.1_benchmark_report.md"
    report = render_report(info, results, seed=42)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(report, encoding="utf-8")
    print(f"\nReport saved: {out_path}")


if __name__ == "__main__":
    main()
